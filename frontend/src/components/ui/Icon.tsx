export type IconName = keyof typeof icons;

/** Small Lucide stroke icon; decorative unless the parent labels it. */
export function Icon({
  name,
  size = 16,
  strokeWidth = name === 'grip' ? 2.4 : 1.8,
  className,
}: {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string | undefined;
}) {
  const Glyph = icons[name];
  return (
    <Glyph
      className={cn('icon shrink-0', className)}
      size={size}
      strokeWidth={strokeWidth}
      aria-hidden="true"
      focusable="false"
    />
  );
}

/** Original Wayseed silhouette; the optical 16 px drawing keeps its channel open in toolbars. */
export function BrandMark({ size = 18, className }: { size?: number; className?: string }) {
  const small = size <= 20;
  const vane = small
    ? 'M3 9C1 5 4 2 7 2C10 1 12 3 13 5C9 4 6 5 5 8L4 10Z'
    : 'M10 36C5 23 14 8 29 7C39 6 49 11 54 20C41 17 28 20 23 30L17 41Z';
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      className={cn('shrink-0', className)}
      width={size}
      height={size}
      viewBox={small ? '0 0 16 16' : '0 0 64 64'}
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      <path d={vane} />
      <path d={vane} transform={small ? 'rotate(180 8 8)' : 'rotate(180 32 32)'} />
      <path d={small ? 'M8 6L9 8L8 10L7 8Z' : 'M32 25L36 32L32 39L28 32Z'} />
    </svg>
  );
}
